export function romanFor(card: CardDef) {
  return card.arcana === 'major' ? ROMAN[card.rank] : '';
}

const NUM_WORD = ['', 'a single', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten'];
const PIP_OBJECT: Record<Suit, [string, string]> = {
  wands: ['staff', 'staves'],
  cups: ['cup', 'cups'],
  swords: ['sword', 'swords'],
  pentacles: ['coin', 'coins'],
};
const PIP_SETTING: Record<Suit, string> = {
  wands: 'crossed and bound among budding leaves',
  cups: 'set in quiet order among curling vines',
  swords: 'curved and interlaced around a single flower',
  pentacles: 'turning within a ribbon of leaves',
};

/** Scene text for decks whose numbered minors are pips (e.g. Marseille). */
export function pipImage(card: CardDef): string {
  if (card.arcana === 'major' || card.rank > 10 || !card.suit) return card.image;
  const [one, many] = PIP_OBJECT[card.suit];
  if (card.rank === 1) return `${NUM_WORD[1]} great ${one}, ornate as a cathedral, rising from the card`;
  return `${NUM_WORD[card.rank]} ${many} ${PIP_SETTING[card.suit]}`;
}
