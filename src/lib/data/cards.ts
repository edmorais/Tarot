// The 78 cards of the tarot. Ids follow Rider–Waite–Smith numbering
// (Strength = 8, Justice = 11); the Marseille deck maps onto these ids.
//
// Fields used by the story engine:
//   image   – a vivid scene, lowercase clause, no final period
//   up/rev  – meaning in full sentences, addressed to the querent
//   lesson  – imperative advice, lowercase, no final period

export type Suit = 'wands' | 'cups' | 'swords' | 'pentacles';
export type Element = 'Fire' | 'Water' | 'Air' | 'Earth';

export interface CardDef {
  id: string;
  name: string;
  arcana: 'major' | 'minor';
  suit?: Suit;
  /** 0–21 for majors, 1–14 for minors (11 Page, 12 Knight, 13 Queen, 14 King) */
  rank: number;
  element: Element;
  kwUp: string[];
  kwRev: string[];
  image: string;
  up: string;
  rev: string;
  lesson: string;
}

export const SUIT_ELEMENT: Record<Suit, Element> = {
  wands: 'Fire',
  cups: 'Water',
  swords: 'Air',
  pentacles: 'Earth',
};

export const SUIT_NAME: Record<Suit, string> = {
  wands: 'Wands',
  cups: 'Cups',
  swords: 'Swords',
  pentacles: 'Pentacles',
};

const RANK_NAME = ['', 'Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Page', 'Knight', 'Queen', 'King'];
const ROMAN = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII', 'XIV', 'XV', 'XVI', 'XVII', 'XVIII', 'XIX', 'XX', 'XXI'];

const pad = (n: number) => String(n).padStart(2, '0');

type Row = [kwUp: string, kwRev: string, image: string, up: string, rev: string, lesson: string];

function major(rank: number, name: string, element: Element, r: Row): CardDef {
  return {
    id: `major-${pad(rank)}`, name, arcana: 'major', rank, element,
    kwUp: r[0].split(', '), kwRev: r[1].split(', '), image: r[2], up: r[3], rev: r[4], lesson: r[5],
  };
}

function suit(s: Suit, rows: Row[]): CardDef[] {
  return rows.map((r, i) => ({
    id: `${s}-${pad(i + 1)}`, name: `${RANK_NAME[i + 1]} of ${SUIT_NAME[s]}`, arcana: 'minor' as const, suit: s,
    rank: i + 1, element: SUIT_ELEMENT[s],
    kwUp: r[0].split(', '), kwRev: r[1].split(', '), image: r[2], up: r[3], rev: r[4], lesson: r[5],
  }));
}

